#!/usr/bin/env python
import sys
import warnings
from datetime import date

from stck_analyzer.crew import StockAnalyzerCrew

from pathlib import Path
from datetime import date

warnings.filterwarnings("ignore", category=SyntaxWarning, module="pysbd")


def run():
    ticker = sys.argv[1] if len(sys.argv) > 1 else 'NVDA'
    today = date.today().isoformat()
    inputs = {'ticker': ticker, 'today': today}

    result = StockAnalyzerCrew().crew().kickoff(inputs=inputs)

    out = Path('briefs')
    out.mkdir(exist_ok=True)
    (out / f'{today}-{ticker}.md').write_text(
        f'# {ticker} daily brief ({today})\n\n{result.raw}\n\n'
        '_Generated by an AI system from public headlines. Not financial advice._\n',
        encoding='utf-8',
    )


def _inputs():
    return {
        "ticker": "NVDA",
        "today": date.today().isoformat(),
    }

