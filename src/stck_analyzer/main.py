def train():
    StockAnalyzerCrew().crew().train(
        n_iterations=int(sys.argv[1]),
        filename=sys.argv[2],
        inputs=_inputs(),
    )


def replay():
    StockAnalyzerCrew().crew().replay(task_id=sys.argv[1])


def test():
    StockAnalyzerCrew().crew().test(
        n_iterations=int(sys.argv[1]),
        eval_llm=sys.argv[2],
        inputs=_inputs(),
    )


if __name__ == '__main__':
    run()